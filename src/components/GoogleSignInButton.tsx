export default function GoogleSignInButton({ next = "/app" }: { next?: string }) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleGoogle() {
    setError(null);
    setBusy(true);
    const supabase = createClient();
    const { error } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo: `${window.location.origin}/auth/callback?next=${encodeURIComponent(next)}`,
      },
    });
    if (error) {
      setError(error.message);
      setBusy(false);
    }
    // On success Supabase redirects the browser to Google, so there is
    // nothing more to do here.
  }

  return (
    <div>
      <button
        type="button"
        onClick={handleGoogle}
        disabled={busy}
        className="btn-glass flex w-full items-center justify-center gap-3 border border-ink/15 bg-white/80 px-6 py-3 text-ink disabled:opacity-60"
      >
        <GoogleMark />
        {busy ? "Connecting to Google..." : "Continue with Google"}
      </button>
      {error && (
        <p className="mt-4 rounded-xl bg-[#f6e3df] px-4 py-3 text-sm font-medium text-[#8c3b2e]">
          {error}
        </p>
      )}
    </div>
  );
}
